CREATE TABLE enrollment_status (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    tenant_id INTEGER NOT NULL REFERENCES master(id),

    name VARCHAR(50) NOT NULL,
    description VARCHAR(255) NULL,

    stop_fee_accrual BOOLEAN NOT NULL DEFAULT FALSE,

    note TEXT NULL,

    date_created TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modified TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE enrollment (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    tenant_id INTEGER NOT NULL REFERENCES master(id),

    student_id INTEGER NOT NULL REFERENCES student(id),
    lesson_id INTEGER NOT NULL REFERENCES lesson(id),

    status_id INTEGER NOT NULL REFERENCES enrollment_status(id),


    date_enrolled TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_unenrolled TIMESTAMPTZ NULL,

    date_created TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modified TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);